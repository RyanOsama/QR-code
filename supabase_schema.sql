-- 10. إجراء تسجيل الدخول الموحد لجميع المنصات مع فحص الاشتراك والحالة (Login RPC)
CREATE OR REPLACE FUNCTION login_app_user(
    p_username TEXT,
    p_password TEXT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_user RECORD;
    v_input_hash TEXT;
BEGIN
    v_input_hash := encode(digest(TRIM(p_password), 'sha256'), 'hex');

    SELECT u.*, c.name as comp_name, c.logo_url as comp_logo, c.status as comp_status,
           s.status as sub_status, s.expiration_date as sub_expiration, s.plan_name as sub_plan
    INTO v_user
    FROM app_users u
    LEFT JOIN companies c ON u.company_id = c.id
    LEFT JOIN tenant_subscriptions s ON s.company_id = c.id
    WHERE LOWER(TRIM(u.username)) = LOWER(TRIM(p_username));

    IF NOT FOUND THEN
        RETURN jsonb_build_object('success', false, 'error', 'اسم المستخدم غير موجود');
    END IF;

    -- التحقق من كلمة المرور: إما تطابق الهاش أو كلمة المرور المؤقتة المسجلة
    IF v_user.password_hash <> v_input_hash AND (v_user.temp_password IS NULL OR v_user.temp_password <> TRIM(p_password)) THEN
        RETURN jsonb_build_object('success', false, 'error', 'كلمة المرور غير صحيحة');
    END IF;

    -- التحقق من حالة الشركة لغير السوبر أدمن
    IF v_user.role <> 'SUPER_ADMIN' THEN
        IF v_user.comp_status = 'SUSPENDED' OR v_user.comp_status = 'INACTIVE' THEN
            RETURN jsonb_build_object('success', false, 'error', 'يرجى التواصل مع الإدارة');
        END IF;

        -- التحقق من حالة الاشتراك
        IF v_user.sub_status IS NOT NULL AND (v_user.sub_status = 'suspended' OR v_user.sub_status = 'expired' OR v_user.sub_status = 'cancelled') THEN
            RETURN jsonb_build_object('success', false, 'error', 'تم تعليق الاشتراك - يرجى التواصل مع الإدارة لتجديد الاشتراك');
        END IF;
    END IF;

    RETURN jsonb_build_object(
        'success', true,
        'user', jsonb_build_object(
            'id', v_user.id,
            'company_id', v_user.company_id,
            'username', v_user.username,
            'full_name', v_user.full_name,
            'role', v_user.role,
            'must_change_password', v_user.must_change_password,
            'temp_password', v_user.temp_password,
            'company_name', v_user.comp_name,
            'company_logo', v_user.comp_logo,
            'company_status', v_user.comp_status,
            'subscription_status', v_user.sub_status
        )
    );
END;
$$;

-- 9. إجراء تغيير كلمة المرور وإلغاء كلمة المرور المؤقتة
CREATE OR REPLACE FUNCTION change_app_user_password(
    p_user_id BIGINT,
    p_new_password TEXT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_new_hash TEXT;
BEGIN
    IF LENGTH(TRIM(p_new_password)) < 4 THEN
        RETURN jsonb_build_object('success', false, 'error', 'كلمة المرور يجب أن لا تقل عن 4 خانات');
    END IF;

    v_new_hash := encode(digest(TRIM(p_new_password), 'sha256'), 'hex');

    UPDATE app_users
    SET password_hash = v_new_hash,
        temp_password = NULL,
        must_change_password = FALSE
    WHERE id = p_user_id;

    IF NOT FOUND THEN
        RETURN jsonb_build_object('success', false, 'error', 'المستخدم غير موجود');
    END IF;

    RETURN jsonb_build_object('success', true);
END;
$$;

-- 10. الدالة الذرية المطورة لفحص وتأكيد الدخول وتسجيل اسم الموظف
CREATE OR REPLACE FUNCTION check_in_atomic(
    p_token TEXT,
    p_event_id BIGINT,
    p_device_name TEXT DEFAULT NULL,
    p_scanned_by TEXT DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_inv RECORD;
    v_now TEXT := to_char(NOW(), 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"');
    v_prev_scan RECORD;
    v_scanner_label TEXT := COALESCE(NULLIF(TRIM(p_scanned_by), ''), 'الموظف المسؤول');
BEGIN
    -- قفل الصف فورياً لمنع أي جهاز آخر من التعديل عليه في نفس اللحظة (Row-level Lock)
    SELECT * INTO v_inv
    FROM invitations
    WHERE token = TRIM(p_token)
    FOR UPDATE;

    -- 1. الرمز غير موجود بتاتاً
    IF NOT FOUND THEN
        INSERT INTO scan_logs (invitation_id, event_id, scanned_at, result, device_name, scanned_by_name, notes)
        VALUES (NULL, p_event_id, v_now, 'INVALID', p_device_name, v_scanner_label, 'رمز QR غير معروف: ' || SUBSTRING(p_token, 1, 15));
        
        RETURN jsonb_build_object(
            'success', false,
            'result', 'INVALID',
            'message', 'رمز الدعوة غير صالح أو غير موجود في النظام!'
        );
    END IF;

    -- 2. الرمز تابع لمناسبة أخرى
    IF v_inv.event_id <> p_event_id THEN
        INSERT INTO scan_logs (invitation_id, event_id, scanned_at, result, device_name, scanned_by_name, notes)
        VALUES (v_inv.id, p_event_id, v_now, 'WRONG_EVENT', p_device_name, v_scanner_label, 'دعوة تابعة لمناسبة أخرى');

        RETURN jsonb_build_object(
            'success', false,
            'result', 'WRONG_EVENT',
            'message', 'هذه الدعوة مخصصة لمناسبة أخرى ولا تتبع هذه المناسبة!',
            'guestName', v_inv.guest_name,
            'invitationNumber', v_inv.invitation_number
        );
    END IF;

    -- 3. الرمز مستخدم مسبقاً (جلب من قام بالمسح السابق)
    IF v_inv.status = 'USED' THEN
        SELECT scanned_by_name, scanned_at INTO v_prev_scan
        FROM scan_logs
        WHERE invitation_id = v_inv.id AND result = 'ACCEPTED'
        ORDER BY id DESC
        LIMIT 1;

        INSERT INTO scan_logs (invitation_id, event_id, scanned_at, result, device_name, scanned_by_name, notes)
        VALUES (
            v_inv.id, 
            p_event_id, 
            v_now, 
            'ALREADY_USED', 
            p_device_name, 
            v_scanner_label, 
            'محاولة دخول مكررة لدعوة ممسوحة سابقاً بواسطة: ' || COALESCE(v_prev_scan.scanned_by_name, 'غير محدد')
        );

        RETURN jsonb_build_object(
            'success', false,
            'result', 'ALREADY_USED',
            'message', 'تم استخدام هذه الدعوة مسبقاً! يرجى منع الدخول.',
            'previousUsedAt', COALESCE(v_prev_scan.scanned_at, v_inv.used_at),
            'scannedBy', v_prev_scan.scanned_by_name,
            'guestName', v_inv.guest_name,
            'invitationNumber', v_inv.invitation_number
        );
    END IF;

    -- 4. الرمز ملغي
    IF v_inv.status = 'CANCELLED' THEN
        INSERT INTO scan_logs (invitation_id, event_id, scanned_at, result, device_name, scanned_by_name, notes)
        VALUES (v_inv.id, p_event_id, v_now, 'INVALID', p_device_name, v_scanner_label, 'دعوة ملغاة');

        RETURN jsonb_build_object(
            'success', false,
            'result', 'INVALID',
            'message', 'هذه الدعوة تم إلغاؤها من قبل الإدارة!',
            'guestName', v_inv.guest_name,
            'invitationNumber', v_inv.invitation_number
        );
    END IF;

    -- 5. رمز سليم وغير مستخدم -> تحديث ذرّي فوري
    UPDATE invitations
    SET status = 'USED', used_at = v_now
    WHERE id = v_inv.id AND status = 'UNUSED';

    -- تسجيل الحركة في السجلات مع اسم الموظف
    INSERT INTO scan_logs (invitation_id, event_id, scanned_at, result, device_name, scanned_by_name, notes)
    VALUES (v_inv.id, p_event_id, v_now, 'ACCEPTED', p_device_name, v_scanner_label, 'دخول مصرح - الدعوة #' || v_inv.invitation_number);

    RETURN jsonb_build_object(
        'success', true,
        'result', 'ACCEPTED',
        'message', 'تم قبول الدخول بنجاح. أهلاً وسهلاً!',
        'guestName', v_inv.guest_name,
        'invitationNumber', v_inv.invitation_number,
        'scannedBy', v_scanner_label,
        'used_at', v_now
    );
END;
$$;

-- 11. دالة تصفير الباركودات المستخدمة
CREATE OR REPLACE FUNCTION reset_used_invitations(p_event_id BIGINT)
RETURNS JSONB
LANGUAGE plpgsql
AS $$
DECLARE
    v_count INTEGER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM invitations WHERE event_id = p_event_id AND status = 'USED';

    UPDATE invitations 
    SET status = 'UNUSED', used_at = NULL 
    WHERE event_id = p_event_id AND status = 'USED';

    DELETE FROM scan_logs WHERE event_id = p_event_id;

    RETURN jsonb_build_object('success', true, 'resetCount', v_count);
END;
$$;

