-- انسخ كامل هذا الملف والصقه في متصفح Supabase في قسم (SQL Editor) ثم اضغط Run.

CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- 1. إنشاء جدول الشركات (companies)
CREATE TABLE IF NOT EXISTS companies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    logo_url TEXT,
    status TEXT NOT NULL DEFAULT 'ACTIVE', -- ACTIVE | INACTIVE
    created_at TEXT NOT NULL DEFAULT to_char(NOW(), 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
);

-- 2. إنشاء جدول المستخدمين والموظفين (app_users)
CREATE TABLE IF NOT EXISTS app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT REFERENCES companies(id) ON DELETE CASCADE,
    username TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    temp_password TEXT,
    full_name TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'EMPLOYEE', -- SUPER_ADMIN | COMPANY_OWNER | EMPLOYEE
    must_change_password BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TEXT NOT NULL DEFAULT to_char(NOW(), 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
);

-- 3. جدول المناسبات (events)
CREATE TABLE IF NOT EXISTS events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT REFERENCES companies(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    date TEXT NOT NULL,
    capacity INTEGER NOT NULL,
    status TEXT NOT NULL DEFAULT 'ACTIVE',
    time TEXT,
    venue TEXT,
    "eventType" TEXT DEFAULT 'wedding',
    created_at TEXT NOT NULL DEFAULT to_char(NOW(), 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
    updated_at TEXT NOT NULL DEFAULT to_char(NOW(), 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
);

-- إضافة عمود company_id لجدول events في حال كان الجدول موجوداً مسبقاً
ALTER TABLE events ADD COLUMN IF NOT EXISTS company_id BIGINT REFERENCES companies(id) ON DELETE CASCADE;

-- 4. جدول الدعوات (invitations)
CREATE TABLE IF NOT EXISTS invitations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    invitation_number INTEGER NOT NULL,
    token TEXT NOT NULL UNIQUE,
    guest_name TEXT,
    graduate_name TEXT,
    has_name INTEGER NOT NULL DEFAULT 0,
    status TEXT NOT NULL DEFAULT 'UNUSED', -- UNUSED | USED | CANCELLED
    created_at TEXT NOT NULL DEFAULT to_char(NOW(), 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
    used_at TEXT
);

-- 5. جدول سجلات المسح (scan_logs)
CREATE TABLE IF NOT EXISTS scan_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invitation_id BIGINT REFERENCES invitations(id) ON DELETE SET NULL,
    event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    scanned_at TEXT NOT NULL DEFAULT to_char(NOW(), 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
    result TEXT NOT NULL, -- ACCEPTED | ALREADY_USED | INVALID | WRONG_EVENT
    device_name TEXT,
    scanned_by_name TEXT,
    scanned_by_id BIGINT REFERENCES app_users(id) ON DELETE SET NULL,
    notes TEXT
);

-- إضافة الأعمدة الإضافية لسجلات المسح إذا كان الجدول منشأ سابقاً
ALTER TABLE scan_logs ADD COLUMN IF NOT EXISTS scanned_by_name TEXT;
ALTER TABLE scan_logs ADD COLUMN IF NOT EXISTS scanned_by_id BIGINT REFERENCES app_users(id) ON DELETE SET NULL;

-- 6. جدول الاشتراكات ونموذج SaaS (tenant_subscriptions)
CREATE TABLE IF NOT EXISTS tenant_subscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT UNIQUE NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
    plan_name TEXT NOT NULL DEFAULT 'Professional',
    billing_cycle TEXT NOT NULL DEFAULT 'monthly', -- monthly | yearly
    status TEXT NOT NULL DEFAULT 'active', -- active | trial | past_due | suspended | cancelled | expired
    start_date TEXT NOT NULL DEFAULT to_char(NOW(), 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
    renewal_date TEXT NOT NULL DEFAULT to_char(NOW() + interval '1 year', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
    expiration_date TEXT NOT NULL DEFAULT to_char(NOW() + interval '1 year', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
    payment_status TEXT NOT NULL DEFAULT 'paid',
    created_at TEXT NOT NULL DEFAULT to_char(NOW(), 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
    updated_at TEXT NOT NULL DEFAULT to_char(NOW(), 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
);

-- 7. جدول إعدادات النشر وترخيص التثبيت المخصص
CREATE TABLE IF NOT EXISTS system_deployment_config (
    id BIGINT PRIMARY KEY DEFAULT 1,
    deployment_mode TEXT NOT NULL DEFAULT 'saas', -- saas | dedicated | local_dev
    database_type TEXT NOT NULL DEFAULT 'hosted_supabase',
    database_url TEXT DEFAULT '',
    database_anon_key TEXT DEFAULT '',
    device_name TEXT DEFAULT 'بوابة 1',
    updated_at TEXT NOT NULL DEFAULT to_char(NOW(), 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
);

CREATE TABLE IF NOT EXISTS dedicated_licenses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT REFERENCES companies(id) ON DELETE SET NULL,
    company_name TEXT NOT NULL,
    license_key TEXT NOT NULL UNIQUE,
    status TEXT NOT NULL DEFAULT 'active', -- active | expired | suspended
    issued_at TEXT NOT NULL DEFAULT to_char(NOW(), 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
    expires_at TEXT,
    notes TEXT
);

CREATE TABLE IF NOT EXISTS licenses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    license_key_hash TEXT NOT NULL UNIQUE,
    company_name TEXT NOT NULL,
    license_type TEXT NOT NULL DEFAULT 'PERPETUAL', -- PERPETUAL | SUBSCRIPTION
    status TEXT NOT NULL DEFAULT 'active', -- active | revoked | expired | suspended
    max_devices INTEGER NOT NULL DEFAULT 1,
    expires_at TEXT,
    created_at TEXT NOT NULL DEFAULT to_char(NOW(), 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
);

CREATE TABLE IF NOT EXISTS license_activations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    license_id BIGINT NOT NULL REFERENCES licenses(id) ON DELETE CASCADE,
    device_id_hash TEXT NOT NULL,
    device_name TEXT,
    activated_at TEXT NOT NULL DEFAULT to_char(NOW(), 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
    last_seen_at TEXT NOT NULL DEFAULT to_char(NOW(), 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
    deactivated_at TEXT
);

-- 7b. جدول تتبع إصدارات مخطط قاعدة البيانات والترقيات (database_schema_version)
CREATE TABLE IF NOT EXISTS database_schema_version (
    version INTEGER PRIMARY KEY,
